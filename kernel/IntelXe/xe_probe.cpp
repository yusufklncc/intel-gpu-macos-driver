// SPDX-License-Identifier: MIT
// XeProbe: staged bring-up probe for Intel Xe GPUs the driver does not support yet. Design: docs/PROBE-MODE.md in
// the public repo (intel-gpu-macos-driver).
//
// The class sits in IntelXe.kext as a second personality. It attaches only to the device named by the boot-arg
// xeprobe=0xDEVICE, does nothing at attach, and runs one stage at a time when root asks through sysctl:
//
//   sysctl debug.xeprobe.stage=N     run stage N (it needs the stages before it)
//   sysctl debug.xeprobe.run=N       run stages 1..N, stopping at the first that fails
//   sysctl debug.xeprobe.results     one line per stage (also the registry dictionary XeProbeResults)
//   sysctl debug.xeprobe.log         what the stages did
//
//   1 identity   read only: PCI ids and BARs, GMD_ID (graphics/media/display), stolen memory, GGTT size, the planes
//                the firmware lit and the GGTT entries behind them, GT/GuC state as found
//   2 forcewake  GT (and render) forcewake, fuses, engine discovery, ring registers; forcewake released after
//   3 guc        GuC load with this family's firmware (xe_uc_fw.c table), WOPCM per xe_wopcm.c, CT channel
//   4 store      a context per engine, registered with the GuC; each writes one dword with MI_STORE_DATA_IMM
//   5 readback   CPU reads every dword back; on a discrete GPU also a GPU write to VRAM read through BAR2
//   9 release    GuC reset, GGTT entries restored, memory freed
//
// Rules the code keeps:
// - The display pipe the firmware lit is never touched: no write to the display MMIO ranges (wr() refuses them),
//   no change to a GGTT entry outside the probe's own window, which must not overlap a lit plane's surface and must
//   hold only zero or one repeated (scratch) value before the probe uses it; the entries are put back at release.
// - Stages 2 and up refuse when another GPU driver is attached to the device (IntelXe, Apple's, anything unknown).
// - A watchdog (thread call) turns a stage that does not return within its limit into a panic that names the stage
//   and step (debug.xeprobe.panic_on_stall, default 1), so a stall leaves a panic report instead of a frozen machine.
// - With debug.xeprobe.nvram=1 (or boot-arg -xeprobecrumb; default off) each step writes the NVRAM variable
//   xeprobe-crumb and syncs it before the step runs, so even a whole-machine hang shows where it stopped after the
//   reset. collect-macos.sh --probe reads it on the next boot.
//
// Register offsets, sequences and tables follow Linux drivers/gpu/drm/xe (MIT, Copyright Intel Corporation),
// torvalds/master as of 2026-10-30; each function names the Linux code it follows.

