#!/bin/bash
# SPDX-License-Identifier: MIT
# gen.sh: compiles the vkscene shaders to SPIR-V (Vulkan 1.3) into spv.h, which is checked in so the build needs no
# shader compiler. Needs glslangValidator (Homebrew's glslang). Run after editing a shader.
set -euo pipefail
cd "$(dirname "$0")"
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
{ echo "// SPDX-License-Identifier: MIT"; echo "// generated by gen.sh from scene.vert, scene.frag, check.vert, check.frag: do not edit"
  echo "#pragma once"; echo "#include <stdint.h>"; } > "$T/spv.h"
for s in scene.vert scene.frag check.vert check.frag; do
    n=${s/./_}_spv
    glslangValidator -V --target-env vulkan1.3 --vn "$n" -o "$T/$n.h" "$s" >/dev/null
    glslangValidator -V --target-env vulkan1.3 -o "$T/$n.spv" "$s" >/dev/null
    if command -v spirv-val >/dev/null; then spirv-val --target-env vulkan1.3 "$T/$n.spv"; fi
    grep -v -e '^[[:space:]]*//' -e 'pragma once' "$T/$n.h" | sed 's/^const uint32_t/static const uint32_t/' >> "$T/spv.h"
done
mv "$T/spv.h" spv.h
echo "spv.h: $(grep -c 'static const uint32_t' spv.h) modules"
