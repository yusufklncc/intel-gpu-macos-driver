"""gen.py OUTDIR: from the SDK's gliDispatch.h and libGL's exports generate
  map.c       measures which gl* symbol goes to which dispatch entry (a numbered trap in every entry, call every symbol)
  thunks.h    one thunk per entry: same signature as the table (GLIContext first), calls backend[i] without the GLIContext
  check.c     a test backend: backend[i] puts the context back and calls Apple's original entry, then a real rendering
  fake_backend.h  the same backend for ../cgl-zink/fakeegl.c
The GL names a backend (zink) needs come from map.tsv, which map.c writes."""
import os, re, subprocess, sys
out = sys.argv[1]; os.makedirs(out, exist_ok=True)
sdk = subprocess.check_output(['xcrun', '--show-sdk-path'], text=True).strip()
h = open(f'{sdk}/System/Library/Frameworks/OpenGL.framework/Headers/gliDispatch.h').read()
body = h[h.index('typedef struct __GLIFunctionDispatchRec'):]; body = body[body.index('{') + 1:body.index('} GLIFunctionDispatch')]
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S); body = re.sub(r'//[^\n]*', '', body)
entries = []
for m in re.finditer(r'([A-Za-z_][\w \*]*?)\s*\(\s*\*\s*(\w+)\s*\)\s*\((.*?)\)\s*;', body, re.S):
    ret, name, args = ' '.join(m.group(1).split()), m.group(2), ' '.join(m.group(3).split())
    parts = [a.strip() for a in args.split(',')]
    assert parts[0].startswith('GLIContext'), name
    rest = []
    for i, a in enumerate(parts[1:]):
        if a == 'void': continue
        am = re.match(r'^(.*?)(\w+)\s*(\[[^\]]*\])?$', a)
        t, n, arr = am.group(1).strip(), am.group(2), am.group(3) or ''
        if not t: t, n = n, f'a{i}'                      # a parameter with no name
        rest.append((t + (' *' if arr else ''), n))
    entries.append((ret, name, rest))
n = len(entries)
print(f'{n} entries')
exports = subprocess.check_output(['dyld_info', '-exports', '/System/Library/Frameworks/OpenGL.framework/Versions/A/Libraries/libGL.dylib'], text=True)
syms = sorted({l.split()[1][1:] for l in exports.splitlines() if re.search(r'\s_gl[A-Z]', l)})
print(f'{len(syms)} gl symbols')
com = '#define GL_SILENCE_DEPRECATION\n#include <OpenGL/OpenGL.h>\n#include <OpenGL/CGLContext.h>\n#include <dlfcn.h>\n#include <stdio.h>\n#include <string.h>\n#include <stdint.h>\n'
with open(f'{out}/map.c', 'w') as f:
    f.write(com + '#include <setjmp.h>\n#include <signal.h>\nstatic volatile int hit; static sigjmp_buf jb;\n')
    f.write('static void onsig(int s) { siglongjmp(jb, 1); }\n')
    for i in range(n): f.write(f'static uintptr_t t{i}(void) {{ hit = {i}; return 0; }}\n')
    f.write('static void *traps[] = {' + ','.join(f't{i}' for i in range(n)) + '};\n')
    f.write('static const char *names[] = {' + ','.join(f'"{e[1]}"' for e in entries) + '};\n')
    f.write('static const char *syms[] = {' + ','.join(f'"{s}"' for s in syms) + '};\n')
    f.write('''int main(void) {
    CGLPixelFormatAttribute a[] = { kCGLPFAAccelerated, 0 }; CGLPixelFormatObj pf; GLint np; CGLChoosePixelFormat(a, &pf, &np);
    CGLContextObj c; CGLCreateContext(pf, 0, &c); CGLSetCurrentContext(c);
    if (sizeof c->disp != sizeof traps) { fprintf(stderr, "table %zu, generated %zu\\n", sizeof c->disp, sizeof traps); return 2; }
    GLIFunctionDispatch saved = c->disp; memcpy(&c->disp, traps, sizeof traps);
    signal(SIGSEGV, onsig); signal(SIGBUS, onsig); signal(SIGILL, onsig);
    int mapped = 0, other = 0, crash = 0;
    for (size_t i = 0; i < sizeof syms / sizeof *syms; i++) {
        void (*f)(uintptr_t, uintptr_t, uintptr_t, uintptr_t) = (void (*)(uintptr_t, uintptr_t, uintptr_t, uintptr_t))dlsym(RTLD_DEFAULT, syms[i]);
        hit = -1;
        if (!f) { printf("%s\\tNOSYM\\n", syms[i]); other++; continue; }
        if (sigsetjmp(jb, 1)) { printf("%s\\tCRASH\\n", syms[i]); crash++; continue; }
        f(0, 0, 0, 0);
        if (hit >= 0) { printf("%s\\t%d\\t%s\\n", syms[i], hit, names[hit]); mapped++; } else { printf("%s\\tNOTABLE\\n", syms[i]); other++; }
    }
    c->disp = saved;
    fprintf(stderr, "symbols %zu: through the table %d, not through it %d, crashed %d\\n", sizeof syms / sizeof *syms, mapped, other, crash);
    return 0; }
''')
# GLhandleARB needs no conversion: Mesa built on macOS has it pointer-sized too (include/GL/glext.h, __APPLE__: unsigned long).
with open(f'{out}/thunks.h', 'w') as f:
    f.write('// generated by gen.py from gliDispatch.h: do not edit\n')
    f.write(f'#define CGLT_N {n}\nextern void *cglt_backend[CGLT_N];\n')
    for i, (ret, name, rest) in enumerate(entries):
        decl = ''.join(f', {t} {a}' for t, a in rest)
        types = ', '.join(t for t, a in rest) or 'void'
        call = ', '.join(a for t, a in rest)
        f.write(f'static {ret} cglt_{name}(GLIContext c_{decl}) {{ CGLT_ENTER(c_); {"return " if ret != "void" else ""}(({ret} (*)({types}))cglt_backend[{i}])({call}); }}\n')
    f.write('static void *cglt_table[CGLT_N] = {' + ','.join(f'(void *)cglt_{e[1]}' for e in entries) + '};\n')
    # Marking wrappers (only with CGLT_MARK defined): a backend entry put behind one runs CGLT_MARK(i) first, then the
    # entry it replaced (cglt_marked[i]). The layer uses them to note "this context drew" without touching other entries.
    f.write('#ifdef CGLT_MARK\nstatic void *cglt_marked[CGLT_N];\n')
    for i, (ret, name, rest) in enumerate(entries):
        decl = ', '.join(f'{t} {a}' for t, a in rest) or 'void'
        types = ', '.join(t for t, a in rest) or 'void'
        call = ', '.join(a for t, a in rest)
        f.write(f'static {ret} cglt_m_{name}({decl}) {{ CGLT_MARK({i}); {"return " if ret != "void" else ""}(({ret} (*)({types}))cglt_marked[{i}])({call}); }}\n')
    f.write('static void *cglt_mark_table[CGLT_N] = {' + ','.join(f'(void *)cglt_m_{e[1]}' for e in entries) + '};\n#endif\n')
def back_function(table, rend, ret, name, rest):
    """A backend function as a real GL would have it: no context; it calls Apple's entry of `table`."""
    decl = ', '.join(f'{t} {a}' for t, a in rest) or 'void'
    call = ''.join(f', {a}' for t, a in rest)
    return f'static {ret} back_{name}({decl}) {{ {"return " if ret != "void" else ""}{table}.{name}({rend}{call}); }}'
with open(f'{out}/fake_backend.h', 'w') as f:
    f.write('// generated by gen.py: test backend, the GL functions of Apple\'s context g_fake_table/g_fake_rend\n')
    for ret, name, rest in entries:
        f.write(back_function('(*g_fake_table)', 'g_fake_rend', ret, name, rest) + '\n')
    f.write('static void *fake_backs[] = {' + ','.join(f'(void *)back_{e[1]}' for e in entries) + '};\n')
with open(f'{out}/check.c', 'w') as f:
    f.write(com + '''#include <OpenGL/gl3.h>
#include <stdlib.h>
static GLIContext g_rend; static GLIFunctionDispatch g_orig; static uint64_t g_calls;
#define CGLT_ENTER(c) do { g_calls++; } while (0)
#include "thunks.h"
void *cglt_backend[CGLT_N];
''')
    for i, (ret, name, rest) in enumerate(entries):
        f.write(back_function('g_orig', 'g_rend', ret, name, rest) + '\n')
    f.write('static void *backs[CGLT_N] = {' + ','.join(f'(void *)back_{e[1]}' for e in entries) + '};\n')
    f.write(r'''
static const char *VS = "#version 410 core\nout vec2 uv; void main(){ vec2 p[3]=vec2[](vec2(-1,-1),vec2(3,-1),vec2(-1,3)); gl_Position=vec4(p[gl_VertexID],0,1); uv=p[gl_VertexID]; }\n";
static const char *FS = "#version 410 core\nin vec2 uv; uniform vec4 k; uniform sampler2D t; layout(location=0) out vec4 o; void main(){ o = k*vec4(uv*0.5+0.5, 0.25, 1) + 0.5*texture(t, uv*0.5+0.5); }\n";
static uint64_t render(GLubyte *px) {
    GLuint v = glCreateShader(GL_VERTEX_SHADER), f = glCreateShader(GL_FRAGMENT_SHADER), p = glCreateProgram(); GLint ok = 0; char log[512];
    glShaderSource(v, 1, &VS, 0); glCompileShader(v); glGetShaderiv(v, GL_COMPILE_STATUS, &ok); if (!ok) { glGetShaderInfoLog(v, 512, 0, log); printf("vs: %s\n", log); }
    glShaderSource(f, 1, &FS, 0); glCompileShader(f); glGetShaderiv(f, GL_COMPILE_STATUS, &ok); if (!ok) { glGetShaderInfoLog(f, 512, 0, log); printf("fs: %s\n", log); }
    glAttachShader(p, v); glAttachShader(p, f); glLinkProgram(p); glGetProgramiv(p, GL_LINK_STATUS, &ok); if (!ok) printf("link failed\n");
    GLuint tex, fbo, rb, vao; GLubyte tp[16] = { 255,0,0,255, 0,255,0,255, 0,0,255,255, 255,255,255,255 };
    glGenTextures(1, &tex); glBindTexture(GL_TEXTURE_2D, tex); glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, 2, 2, 0, GL_RGBA, GL_UNSIGNED_BYTE, tp);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR); glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glGenRenderbuffers(1, &rb); glBindRenderbuffer(GL_RENDERBUFFER, rb); glRenderbufferStorage(GL_RENDERBUFFER, GL_RGBA8, 64, 64);
    glGenFramebuffers(1, &fbo); glBindFramebuffer(GL_FRAMEBUFFER, fbo); glFramebufferRenderbuffer(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_RENDERBUFFER, rb);
    if (glCheckFramebufferStatus(GL_FRAMEBUFFER) != GL_FRAMEBUFFER_COMPLETE) printf("fbo incomplete\n");
    glGenVertexArrays(1, &vao); glBindVertexArray(vao); glViewport(0, 0, 64, 64); glClearColor(0.1f, 0.2f, 0.3f, 1); glClear(GL_COLOR_BUFFER_BIT);
    glUseProgram(p); glUniform4f(glGetUniformLocation(p, "k"), 1.0f, 0.5f, 0.75f, 1.0f); glUniform1i(glGetUniformLocation(p, "t"), 0);
    glDrawArrays(GL_TRIANGLES, 0, 3); glFinish();
    glReadPixels(0, 0, 64, 64, GL_RGBA, GL_UNSIGNED_BYTE, px);
    GLenum e = glGetError(); if (e) printf("glGetError 0x%x\n", e);
    uint64_t s = 1469598103934665603ull; for (int i = 0; i < 64 * 64 * 4; i++) s = (s ^ px[i]) * 1099511628211ull; return s;
}
int main(void) {
    CGLPixelFormatAttribute a[] = { kCGLPFAAccelerated, kCGLPFAOpenGLProfile, (CGLPixelFormatAttribute)kCGLOGLPVersion_GL4_Core, 0 };
    CGLPixelFormatObj pf; GLint np; CGLChoosePixelFormat(a, &pf, &np); CGLContextObj c; CGLCreateContext(pf, 0, &c); CGLSetCurrentContext(c);
    printf("%s | %s\n", glGetString(GL_RENDERER), glGetString(GL_VERSION));
    if (sizeof cglt_table != sizeof c->disp) { printf("table size differs\n"); return 2; }
    static GLubyte p0[64 * 64 * 4], p1[64 * 64 * 4];
    uint64_t s0 = render(p0);
    g_rend = c->rend; g_orig = c->disp; memcpy(cglt_backend, backs, sizeof backs); memcpy(&c->disp, cglt_table, sizeof cglt_table);
    uint64_t s1 = render(p1);
    printf("direct  %016llx\nthunks  %016llx (%llu calls through the thunks)\ncentre  %u %u %u %u\n%s\n", s0, s1, g_calls, p1[32*64*4+32*4], p1[32*64*4+32*4+1], p1[32*64*4+32*4+2], p1[32*64*4+32*4+3],
           s0 == s1 && g_calls > 20 ? "RESULT: identical image through the generated thunks" : "RESULT: DIFFERENT");
    c->disp = g_orig; return s0 != s1;
}
''')
